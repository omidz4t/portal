#!/usr/bin/env node
/** Fetch GitHub releases and write a tiny versions.json for the site build. */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const landing = join(dirname(fileURLToPath(import.meta.url)), '..');
const root = join(landing, '..');
const outFile = join(landing, 'src/lib/versions-data.ts');
const repo = process.env.GITHUB_REPOSITORY || 'omidz4t/portal';

function readCurrent() {
	try {
		return readFileSync(join(root, 'VERSION'), 'utf8').trim().replace(/^v/i, '');
	} catch {
		return '0.0.0';
	}
}

async function fetchReleases() {
	const headers = { Accept: 'application/vnd.github+json', 'User-Agent': 'portal-landing' };
	if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
	const res = await fetch(`https://api.github.com/repos/${repo}/releases?per_page=40`, { headers });
	if (!res.ok) throw new Error(`GitHub releases ${res.status}`);
	const data = await res.json();
	if (!Array.isArray(data)) return [];
	return data
		.filter((r) => r && !r.draft && r.tag_name)
		.map((r) => ({
			tag: String(r.tag_name),
			date: String(r.published_at || r.created_at || '').slice(0, 10)
		}));
}

const current = readCurrent();
let releases = [];
try {
	releases = await fetchReleases();
} catch (err) {
	console.warn('write-versions: using VERSION only —', err.message);
}

if (!releases.some((r) => r.tag.replace(/^v/i, '') === current)) {
	releases = [{ tag: `v${current}`, date: '' }, ...releases];
}

const body = { current, repo, releases };
writeFileSync(
	outFile,
	`// generated by scripts/write-versions.mjs — do not edit\nexport default ${JSON.stringify(body, null, '\t')} as const;\n`
);
console.log(`wrote ${releases.length} versions (current ${current}) → ${outFile}`);
